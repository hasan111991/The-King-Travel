export async function downloadBookingConfirmationPdf(
  booking: BookingRecord,
  agencyName = 'The King Travel'
) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const marginX = 48;
  let y = 52;

  // Header band
  doc.setFillColor(15, 41, 66);
  doc.rect(0, 0, 595, 92, 'F');

  doc.setTextColor(253, 143, 28);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text(agencyName.toUpperCase(), marginX, 44);

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text('Your Ultimate Travel Partner!', marginX, 64);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`REF: ${booking.bookingReference}`, 410, 44);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`MODE: ${booking.mode === 'demo' ? 'DEMO SANDBOX' : 'LIVE BOOKING'}`, 410, 62);

  y = 124;

  // Important notice
  doc.setFillColor(247, 249, 252);
  doc.setDrawColor(217, 226, 236);
  doc.rect(marginX, y, 499, 44, 'FD');
  doc.setTextColor(16, 42, 67);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('IMPORTANT NOTICE — BOOKING CONFIRMATION / INVOICE ONLY', marginX + 12, y + 17);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(
    'This document is an agency booking record and payment invoice. It is NOT an airline-issued e-ticket for boarding.',
    marginX + 12,
    y + 33
  );
  y += 68;

  // Status Summary
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('1. Booking & Payment Status', marginX, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`Booking Reference: ${booking.bookingReference}`, marginX, y);
  doc.text(`Booking Status: ${booking.bookingStatus}`, 310, y);
  y += 16;
  doc.text(`Payment Method: ${booking.paymentMethod}`, marginX, y);
  doc.text(`Payment Status: ${booking.paymentStatus.replace(/_/g, ' ').toUpperCase()}`, 310, y);
  y += 16;
  if (booking.supplierReference) {
    doc.text(`Supplier / PNR Reference: ${booking.supplierReference}`, marginX, y);
    y += 16;
  }
  y += 14;

  // Flight Details
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('2. Itinerary Details', marginX, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const fd = booking.flightDetails || {};
  doc.text(
    `Route: ${fd.originCode || fd.origin || '-'} -> ${fd.destinationCode || fd.destination || '-'}`,
    marginX,
    y
  );
  doc.text(`Airline: ${fd.airline || '-'} (${fd.flightNumber || '-'})`, 310, y);
  y += 16;
  doc.text(`Departure Date: ${fd.departureDate || '-'}`, marginX, y);
  doc.text(`Cabin Class: ${fd.cabinClass || 'Economy'}`, 310, y);
  y += 16;
  doc.text(`Baggage: ${fd.baggageAllowance || 'Per airline tariff'}`, marginX, y);
  doc.text(`Stops: ${typeof fd.stops === 'number' ? fd.stops : '-'}`, 310, y);
  y += 26;

  // Passengers
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('3. Passenger Manifest', marginX, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  (booking.passengers || []).forEach((p, idx) => {
    if (y > 740) {
      doc.addPage();
      y = 52;
    }
    doc.text(
      `${idx + 1}. ${p.firstName} ${p.lastName} (${p.type}) · ${p.gender} · DOB: ${p.dateOfBirth} · Nat: ${p.nationality}`,
      marginX,
      y
    );
    y += 14;
    if (p.passportNumber) {
      doc.setTextColor(72, 101, 129);
      doc.text(`   Passport: ${p.passportNumber} (Exp: ${p.passportExpiry || 'N/A'})`, marginX, y);
      doc.setTextColor(16, 42, 67);
      y += 14;
    }
  });
  y += 14;

  // Fare Breakdown
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('4. Fare Breakdown', marginX, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const fb = booking.fareBreakdown;
  if (fb) {
    doc.text(`Base Fare: ${formatMoney(fb.baseFare, booking.currency)}`, marginX, y);
    y += 16;
    doc.text(`Taxes & Fees: ${formatMoney(fb.taxes, booking.currency)}`, marginX, y);
    y += 16;
    doc.text(`Agency Service Charges: ${formatMoney(fb.serviceCharges, booking.currency)}`, marginX, y);
    y += 18;
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Total Amount: ${formatMoney(booking.totalAmount, booking.currency)}`, marginX, y);

  // Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(98, 125, 152);
  doc.text(
    `Generated by ${agencyName} on ${new Date().toLocaleDateString()} · Customer Contact: ${booking.contactDetails?.email || ''}`,
    marginX,
    790
  );

  doc.save(`${booking.bookingReference}_Confirmation.pdf`);
}

export function downloadCsvReport(filename: string, headers: string[], rows: Array<Array<string | number>>) {
  const escape = (val: string | number) => {
    const str = String(val ?? '');
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };
  const csvContent = [headers.map(escape).join(','), ...rows.map((r) => r.map(escape).join(','))].join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export async function downloadAdminPdfReport(
  title: string,
  subtitle: string,
  headers: string[],
  rows: Array<Array<string | number>>,
  filename: string
) {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4', orientation: 'landscape' });
  doc.setFillColor(15, 41, 66);
  doc.rect(0, 0, 842, 70, 'F');
  doc.setTextColor(253, 143, 28);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('THE KING TRAVEL — EXECUTIVE REPORT', 40, 32);
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`${title} · ${subtitle} · Generated ${new Date().toLocaleString()}`, 40, 52);

  let y = 96;
  const colWidth = Math.floor(760 / Math.max(1, headers.length));

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(16, 42, 67);
  headers.forEach((h, i) => {
    doc.text(String(h).slice(0, 22), 40 + i * colWidth, y);
  });
  y += 8;
  doc.setDrawColor(217, 226, 236);
  doc.line(40, y, 800, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  rows.forEach((row) => {
    if (y > 545) {
      doc.addPage();
      y = 48;
    }
    row.forEach((cell, i) => {
      doc.text(String(cell ?? '').slice(0, 26), 40 + i * colWidth, y);
    });
    y += 16;
  });

  doc.save(filename);
}

export function buildReportData(
  reportType: 'daily' | 'monthly' | 'customers' | 'revenue' | 'payments' | 'cancellations',
  bookings: BookingRecord[],
  payments: PaymentRecord[],
  customers: UserProfile[]
): { headers: string[]; rows: Array<Array<string | number>>; title: string } {
  const todayStr = new Date().toISOString().slice(0, 10);
  const monthStr = new Date().toISOString().slice(0, 7);

  switch (reportType) {
    case 'daily': {
      const filtered = bookings.filter((b) => {
        const ts = b.createdAt?.toDate ? b.createdAt.toDate().toISOString().slice(0, 10) : '';
        return ts === todayStr;
      });
      return {
        title: `Daily Booking Report (${todayStr})`,
        headers: ['Reference', 'Route', 'Mode', 'Total', 'Payment', 'Status'],
        rows: filtered.map((b) => [
          b.bookingReference,
          `${b.flightDetails?.originCode || '-'} -> ${b.flightDetails?.destinationCode || '-'}`,
          b.mode,
          `${b.currency} ${b.totalAmount}`,
          b.paymentStatus,
          b.bookingStatus,
        ]),
      };
    }
    case 'monthly': {
      const filtered = bookings.filter((b) => {
        const ts = b.createdAt?.toDate ? b.createdAt.toDate().toISOString().slice(0, 7) : '';
        return ts === monthStr;
      });
      return {
        title: `Monthly Booking Report (${monthStr})`,
        headers: ['Reference', 'Customer Email', 'Route', 'Total', 'Payment', 'Status'],
        rows: filtered.map((b) => [
          b.bookingReference,
          b.contactDetails?.email || '-',
          `${b.flightDetails?.originCode || '-'} -> ${b.flightDetails?.destinationCode || '-'}`,
          `${b.currency} ${b.totalAmount}`,
          b.paymentStatus,
          b.bookingStatus,
        ]),
      };
    }
    case 'customers':
      return {
        title: 'Registered Customers Report',
        headers: ['Name', 'Email', 'Phone', 'Role', 'Status'],
        rows: customers.map((c) => [c.name, c.email, c.phone || '-', c.role, c.status]),
      };
    case 'revenue': {
      const confirmed = bookings.filter((b) => b.paymentStatus === 'confirmed');
      return {
        title: 'Confirmed Revenue Report',
        headers: ['Reference', 'Airline', 'Method', 'Amount', 'Currency', 'Status'],
        rows: confirmed.map((b) => [
          b.bookingReference,
          b.flightDetails?.airline || '-',
          b.paymentMethod,
          b.totalAmount,
          b.currency,
          b.bookingStatus,
        ]),
      };
    }
    case 'payments':
      return {
        title: 'Payments & Receipt Verification Report',
        headers: ['Payment ID', 'Booking ID', 'Method', 'Reference', 'Amount', 'Status'],
        rows: payments.map((p) => [
          p.paymentId,
          p.bookingId,
          p.paymentMethod,
          p.transactionReference || '-',
          `${p.currency} ${p.amount}`,
          p.verificationStatus,
        ]),
      };
    case 'cancellations': {
      const cancelled = bookings.filter((b) =>
        ['Cancelled', 'Refund Requested', 'Refunded'].includes(b.bookingStatus)
      );
      return {
        title: 'Cancellations & Refunds Report',
        headers: ['Reference', 'Customer', 'Total', 'Status', 'Reason'],
        rows: cancelled.map((b) => [
          b.bookingReference,
          b.contactDetails?.email || '-',
          `${b.currency} ${b.totalAmount}`,
          b.bookingStatus,
          b.refundReason || '-',
        ]),
      };
    }
  }
}
